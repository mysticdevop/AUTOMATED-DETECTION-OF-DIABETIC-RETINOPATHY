# ─── Classification metrics ──────────────────────────────────────────────────
@torch.no_grad()
def evaluate(model: nn.Module, loader: DataLoader) -> dict:
    """Full evaluation: QWK, accuracy, macro-AUC, per-class metrics."""
    model.eval()
    all_preds, all_labels, all_probs = [], [], []

    for imgs, labels in loader:
        imgs = imgs.to(DEVICE)
        with autocast():
            logits = model(imgs)
        probs = F.softmax(logits, dim=1).cpu().numpy()
        preds = logits.argmax(dim=1).cpu().numpy()
        all_probs.extend(probs)
        all_preds.extend(preds)
        all_labels.extend(labels.numpy())

    all_probs  = np.array(all_probs)
    all_preds  = np.array(all_preds)
    all_labels = np.array(all_labels)

    qwk = cohen_kappa_score(all_labels, all_preds,
                             weights='quadratic')
    acc = accuracy_score(all_labels, all_preds)
    auc = roc_auc_score(
        all_labels, all_probs,
        multi_class='ovr', average='macro')

    print(f'QWK  : {qwk:.4f}')
    print(f'Acc  : {acc*100:.2f}%')
    print(f'AUC  : {auc:.4f}')
    print(classification_report(all_labels, all_preds,
          target_names=list(DR_LABELS.values())))
    return {'qwk': qwk, 'acc': acc, 'auc': auc}


# ─── Dice overlap with IDRiD lesion mask ─────────────────────────────────────
def dice_overlap(saliency: np.ndarray,
                  mask: np.ndarray,
                  threshold_pct: float = 80.0) -> float:
    """
    Compute Dice coefficient between thresholded saliency map
    and ground-truth binary lesion mask.
    saliency     : (H, W) float in [0, 1]
    mask         : (H, W) binary {0, 1}
    threshold_pct: percentile to binarize saliency
    """
    thresh = np.percentile(saliency, threshold_pct)
    sal_bin = (saliency >= thresh).astype(float)
    mask_bin = (mask > 0).astype(float)

    intersection = (sal_bin * mask_bin).sum()
    dice = (2.0 * intersection) / \
           (sal_bin.sum() + mask_bin.sum() + 1e-8)
    return float(dice)


# ─── Area Over the Perturbation Curve (AOPC) ─────────────────────────────────
@torch.no_grad()
def compute_aopc(model: nn.Module,
                  img_tensor: torch.Tensor,
                  saliency: np.ndarray,
                  steps: int = 20) -> float:
    """
    Progressively mask top-k% salient pixels and measure
    cumulative confidence drop (AOPC).
    Higher AOPC = saliency correctly identifies critical pixels.
    """
    model.eval()
    img = img_tensor.clone().to(DEVICE)
    H, W = saliency.shape

    # Baseline confidence
    logits   = model(img)
    target   = logits.argmax(dim=1).item()
    baseline = F.softmax(logits, dim=1)[0, target].item()

    # Flatten saliency and sort descending
    flat_sal = saliency.flatten()
    sorted_idx = np.argsort(flat_sal)[::-1]
    n_pixels   = len(flat_sal)
    step_size  = n_pixels // steps

    mean_pixel = img.mean().item()
    drops = []
    masked_img = img.clone()

    for k in range(1, steps + 1):
        n_mask = k * step_size
        idx_to_mask = sorted_idx[:n_mask]
        rows = idx_to_mask // W
        cols = idx_to_mask % W
        # Mask all channels at masked pixels
        masked_img[0, :, rows, cols] = mean_pixel
        with autocast():
            conf = F.softmax(model(masked_img), dim=1)
        conf_k = conf[0, target].item()
        drops.append(baseline - conf_k)

    return float(np.mean(drops))   # AOPC


# ─── Saliency map entropy ─────────────────────────────────────────────────────
def map_entropy(saliency: np.ndarray,
                bins: int = 256) -> float:
    """
    Shannon entropy of the saliency distribution.
    Low entropy = focused attention (clinically preferred).
    """
    hist, _ = np.histogram(saliency, bins=bins,
                            range=(0, 1), density=True)
    hist = hist + 1e-10            # smoothing
    hist = hist / hist.sum()
    return float(-np.sum(hist * np.log2(hist)))